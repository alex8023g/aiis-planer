/// Справочник оборудования: как сравнивать и как записывать названия видов и
/// марок. Без обращений к базе — равенство названий нужно и браузеру: редактор
/// спецификации по нему узнаёт уже заведённый вид и подставляет его ед. изм.

/// Кириллические буквы, неотличимые на глаз от латинских (после перевода в
/// нижний регистр). В марках их путают постоянно: «iRZ ATM42.В» с кириллической
/// В в опросе МЛЗ стоит рядом с латинской.
const LOOKALIKES: Record<string, string> = {
  а: 'a',
  в: 'b',
  е: 'e',
  ё: 'e',
  к: 'k',
  м: 'm',
  н: 'h',
  о: 'o',
  р: 'p',
  с: 'c',
  т: 't',
  у: 'y',
  х: 'x',
};

/// Название в том виде, в каком его хранят: без пробелов по краям и без
/// двойных пробелов внутри. Буквы не трогаем — «ЩМП» должно остаться ЩМП.
export function cleanEquipmentName(value: string): string {
  return value.trim().replace(/\s+/g, ' ');
}

/// Ключ для сравнения: два названия — одно и то же, если ключи равны. Только
/// для сравнения и только в коде: в базе ключа нет, хранят название как
/// набрали (см. cleanEquipmentName), и уникальность там — по нему.
export function equipmentKey(value: string): string {
  return cleanEquipmentName(value)
    .toLowerCase()
    .replace(/[авекмнорстухё]/g, (letter) => LOOKALIKES[letter]);
}
